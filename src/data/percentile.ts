/** 이 점수가 상위 몇 %인지. 1이면 최상위 1%. */
export function topPercentFor(score: number): number {
  const s = Math.max(0, Math.min(100, Math.round(score)))
  const top = (1 - BELOW[s]) * 100
  if (top < 1) return 1
  return Math.round(top)
}

